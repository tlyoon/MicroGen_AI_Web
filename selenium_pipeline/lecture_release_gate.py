"""Read-only final academic and student release gates for MicroGen lectures.

Technical codec/receipt verification is not a lecturer review. This module
never creates approvals. Explicit, separately authored, source-bound human
records are mandatory before claiming an academically accepted lecture; a
second separately authorized record is required for student publication.
"""
from __future__ import annotations

import hashlib
import json
from datetime import datetime
from pathlib import Path

from .production_video_contract import verify_series


class LectureApprovalError(ValueError):
    """The human review or student release has not been established."""


ACADEMIC_REVIEW_FILE = "lecture_human_approval.json"
STUDENT_AUTH_FILE = "lecture_student_publication_authorization.json"
REVIEW_FLAGS = (
    "mathematics_approved",
    "all_figures_complete_and_legible",
    "original_narration_listened_and_approved",
    "spoken_element_highlights_approved",
)


def _require(ok: bool, reason: str) -> None:
    if not ok:
        raise LectureApprovalError(reason)


def _sha(path: Path) -> str:
    _require(path.is_file() and not path.is_symlink(),
             "Missing source-bound approval input: " + str(path))
    h = hashlib.sha256()
    with path.open("rb") as fd:
        for block in iter(lambda: fd.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def _read(path: Path) -> dict:
    _require(path.is_file() and not path.is_symlink(),
             "Missing explicitly authored approval: " + str(path))
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise LectureApprovalError("Unreadable approval record") from exc
    _require(isinstance(value, dict), "Approval record must be an object")
    return value


def _identity(row: dict, actor_field: str) -> None:
    value = row.get(actor_field)
    _require(isinstance(value, str) and len(value.strip()) >= 3,
             f"Explicit {actor_field} required")
    time_str = row.get("approved_at_utc")
    _require(isinstance(time_str, str) and time_str.endswith("Z"),
             "Explicit UTC approval time required")
    try:
        parsed = datetime.fromisoformat(time_str.replace("Z", "+00:00"))
    except ValueError as exc:
        raise LectureApprovalError("Invalid UTC approval time") from exc
    _require(parsed.utcoffset().total_seconds() == 0,
             "UTC approval time required")
    _require(row.get("human_authored_explicit_approval") is True,
             "Automated/implicit review flags are not valid human approval")


def verify_academic_lecture(root: Path, *, probe=None) -> dict:
    """Require technical verification AND explicit math, figure, audio review.

    A valid JSON attestation is a *record* of an owner's claimed review, not
    cryptographic verification of the human identity or listening experience.
    It must not be fabricated/generated by the pipeline.
    """
    folder = Path(root)
    technical = verify_series(folder, probe=probe)
    approval = _read(folder / ACADEMIC_REVIEW_FILE)
    _require(approval.get("schema_version") == 1
             and approval.get("status") == "human_academic_review_approved",
             "No valid explicitly approved academic review status")
    _identity(approval, "reviewed_by")
    for name in REVIEW_FLAGS:
        _require(approval.get(name) is True,
                 f"Independent lecturer acceptance missing: {name}")
    for filename, key in (
        ("source.pdf", "source_sha256"),
        ("slides.pdf", "slides_sha256"),
        ("script.txt", "narration_script_sha256"),
        ("lecture_completion.json", "technical_series_sha256"),
        ("tts_input_manifest.json", "tts_input_manifest_sha256"),
    ):
        _require(approval.get(key) == _sha(folder / filename),
                 f"Academic review not bound to current {filename}")
    # A human cannot approve a single consistent voice from a bare generic
    # MP4 receipt. Require the actual slide-text-to-effective-voice manifest
    # and check every slide against the original, hash-bound script.
    from .runner import blocks
    from .tts_effective_identity import verify_effective_identity, TTSEffectiveIdentityError
    try:
        tts=_read(folder / "tts_input_manifest.json")
        spoken=blocks((folder / "script.txt").read_text(encoding="utf-8"))
        voice=verify_effective_identity(tts, spoken)
    except (ValueError, TTSEffectiveIdentityError, OSError) as exc:
        raise LectureApprovalError(
            "Academic review requires verified source-bound uniform TTS voice") from exc
    _require(approval.get("effective_tts_model") == voice["model"]
             and approval.get("effective_tts_voice") == voice["voice"],
             "Human review not bound to actual effective model/voice")
    _require(approval.get("subject") == "entire_source_bound_lecture",
             "Academic review must cover the complete lecture")
    return {
        "status": "explicit_human_reviewed_lecture",
        "technical_series": technical,
        "human_review_receipt_sha256": _sha(folder / ACADEMIC_REVIEW_FILE),
        "student_publication_permitted": False,
    }


def verify_student_publication(root: Path, *, probe=None) -> dict:
    """Separate, independent explicit permission; never publishes by itself."""
    folder = Path(root)
    reviewed = verify_academic_lecture(folder, probe=probe)
    row = _read(folder / STUDENT_AUTH_FILE)
    _require(row.get("schema_version") == 1
             and row.get("status") == "explicit_student_publication_authorized"
             and row.get("student_publication_permitted") is True,
             "Student publication not explicitly authorized")
    _identity(row, "authorized_by")
    _require(row.get("human_review_receipt_sha256")
             == reviewed["human_review_receipt_sha256"],
             "Student release does not bind to current human review")
    _require(row.get("technical_series_sha256")
             == _sha(folder / "lecture_completion.json"),
             "Student release is stale relative to verified video series")
    return {
        "status": "student_publication_explicitly_authorized",
        "lecture": reviewed,
        "student_publication_permitted": True,
    }
