"""Convert independently reviewed candidate selections into a STAGING plan.

No model, invented audio, guessed source quote or implicit academic approval.
Every slide, exact script fragment, source quote, anchor, WAV and 10-minute
part is revalidated before the final staging-compatible plan can be created.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import re
import wave
from pathlib import Path

import pymupdf

from .element_narration_stage import normalize, rectangle, ElementStageError
from .element_plan_autodraft import propose, file_hash, AutoDraftError


class PlanPromotionError(ValueError):
    pass


def check(condition: bool, message: str) -> None:
    if not condition: raise PlanPromotionError(message)


def load(file: Path) -> dict:
    check(file.is_file() and not file.is_symlink(),f"Missing reviewed input: {file}")
    data=json.loads(file.read_text(encoding="utf8"))
    check(isinstance(data,dict),"Expected JSON evidence object")
    return data


def template(draft: dict) -> dict:
    """Write explicit blanks; never preselect semantically ambiguous matches."""
    check(draft.get("status")=="REVIEW_REQUIRED_NOT_TTS_READY",
          "Not a review-only auto candidate draft")
    return {"schema_version":1,"status":"REVIEW_SELECTION_INCOMPLETE",
            "draft_sha256":None,
            "voice_id":None,
            "tts_model":None,
            "tts_voice":None,
            "reviewer_note":None,
            "academic_approval":False,
            "slides":[{"slide":s["slide_number"],
                       "source_page":None,"source_evidence":None,
                       "title":s["title_hint"] or f"Original slide {s['slide_number']}",
                       "review_note":None,"elements":[]}
                      for s in draft["slides"]],
            "part_boundaries_after_slides":[],
            "warning":"Fill only after inspecting rendered elements and textbook. "
                      "Each element must name exact utterance ids and an existing, final PCM WAV. "
                      "Still NOT academic or student-publication approval."}


def promoted(*,source:Path,slides:Path,script:Path,
             draft_path:Path,selection:Path,audio:Path|None=None,
             prepare_tts:bool=False,tts_request:Path|None=None)->dict:
    source,slides,script,draft_path,selection=(Path(x).resolve() for x in
                 (source,slides,script,draft_path,selection))
    audio=Path(audio).resolve() if audio is not None else None
    check(prepare_tts == (audio is None),
          "Exactly one phase: TTS request without WAVs or final staging with WAVs")
    if not prepare_tts:
        check(audio.is_dir() and not audio.is_symlink(),"Frozen audio folder required")
    draft=load(draft_path)
    decision=load(selection)
    check(draft.get("status")=="REVIEW_REQUIRED_NOT_TTS_READY"
          and draft.get("can_stage_or_synthesize_audio") is False
          and draft["source_sha256"]==file_hash(source)
          and draft["slides_sha256"]==file_hash(slides)
          and draft["script_sha256"]==file_hash(script),
          "Tentative draft is stale or improperly approved")
    # Recompute every utterance and visual candidate from immutable PDFs
    # and narration; a hand-edited draft + freshly forged selection hash
    # must not authorize invented speech or remapped diagram rectangles.
    regenerated=propose(source_pdf=source,slides_pdf=slides,script_txt=script)
    check(draft==regenerated,
          "Autogenerated candidate geometry/speech was modified or stale")
    check(decision.get("schema_version")==1
          and decision.get("status")=="REVIEWED_SELECTION_FOR_PROCESSING"
          and decision.get("draft_sha256")==file_hash(draft_path)
          and decision.get("academic_approval") is False,
          "Reviewer selection missing, unsigned or improperly academic-approved")
    note=decision.get("reviewer_note")
    check(isinstance(note,str) and len(note.strip())>=20,
          "Explicit reviewer rationale required for processing")
    voice=decision.get("voice_id")
    check(isinstance(voice,str) and len(voice)>=6 and "unknown" not in voice.lower(),
          "Model/voice identity must be explicit and consistent")
    declared_model=decision.get("tts_model")
    declared_voice=decision.get("tts_voice")
    check(isinstance(declared_model,str) and declared_model.startswith("gemini-")
          and "-tts" in declared_model and isinstance(declared_voice,str)
          and len(declared_voice)>=3 and declared_model in voice
          and declared_voice in voice,
          "Gemini TTS model and voice must be declared consistently")
    checks=decision.get("slides")
    check(isinstance(checks,list) and len(checks)==draft["slide_count"]
          and [s.get("slide") for s in checks]==list(range(1,len(checks)+1)),
          "Every slide requires ordered explicit reviewer decisions")
    boundaries=decision.get("part_boundaries_after_slides",[])
    check(isinstance(boundaries,list) and len(set(boundaries))==len(boundaries)
          and all(type(i) is int and 1<=i<len(checks) for i in boundaries)
          and boundaries==sorted(boundaries)
          and len(boundaries)<=39,
          "Manually reviewed part boundaries must be unique, ordered and in range")
    authored=[]
    used_wavs=set()
    with pymupdf.open(source) as textbook,pymupdf.open(slides) as deck:
        check(len(deck)==len(checks),"Slide PDF count changed")
        for current,choice in zip(draft["slides"],checks):
            number=current["slide_number"]
            page_index=choice.get("source_page")
            quote=choice.get("source_evidence")
            check(type(page_index) is int and 1<=page_index<=len(textbook),
                  f"Slide {number}: verified source page number missing")
            page_txt=normalize(textbook[page_index-1].get_text())
            check(isinstance(quote,str) and len(normalize(quote))>=12
                  and normalize(quote) in page_txt,
                  f"Slide {number}: literal source evidence not present")
            reason=choice.get("review_note")
            check(isinstance(reason,str) and len(reason.strip())>=15,
                  f"Slide {number}: source mapping reviewer note required")
            anchors={x["draft_element_id"]:x for x in current["auto_candidate_targets"]}
            fragments={x["proposal_id"]:x for x in current["proposed_utterances"]}
            required_ids=list(fragments)
            rows=choice.get("elements")
            check(isinstance(rows,list) and len(rows)>0,
                  f"Slide {number}: narrated visual elements not selected")
            # Validate ALL utterance coverage before testing individual
            # model/audio receipts; missing/reversed words must be reported
            # as structural speech failures, not misidentified TTS failures.
            flattened=[]
            for row in rows:
                ids=row.get("utterance_ids")
                check(isinstance(ids,list) and len(ids)>0
                      and all(isinstance(i,str) and i in fragments for i in ids),
                      f"Slide {number}: missing original script fragments")
                flattened.extend(ids)
            check(flattened==required_ids,
                  f"Slide {number}: missing/repeated/out-of-order original narration words")
            used=[]
            selections=[]
            already_targets=set()
            for row in rows:
                target=row.get("draft_element_id")
                check(target in anchors and target not in already_targets,
                      f"Slide {number}: unrecognized or reused visual target")
                already_targets.add(target)
                ids=row.get("utterance_ids")
                check(isinstance(ids,list) and len(ids)>0
                      and all(isinstance(i,str) and i in fragments for i in ids),
                      f"Slide {number}: missing original script fragments")
                used.extend(ids)
                selected_anchor=anchors[target]["anchor"]
                if anchors[target]["suspected_multipart"]:
                    # Wide multi-panel image: full original figure can be used,
                    # or exact panel bounds require explicit full-panel review.
                    check(row.get("figure_review_acknowledged") is True
                          and len(str(row.get("figure_review_note","")).strip())>=20,
                          f"Slide {number}: ambiguous composite figure needs review")
                override=row.get("anchor_override")
                if override is not None:
                    check(selected_anchor["type"]=="image_whole"
                          and override.get("type")=="image_panel"
                          and override.get("index")==selected_anchor["index"]
                          and type(override.get("panels")) is int
                          and type(override.get("panel")) is int
                          and row.get("figure_review_acknowledged") is True,
                          f"Slide {number}: unsafe figure panel override")
                    selected_anchor=override
                note=row.get("element_review_note")
                check(isinstance(note,str) and len(note.strip())>=15,
                      f"Slide {number}: element matching rationale needed")
                try:
                    rectangle(deck[number-1],selected_anchor)
                except ElementStageError as exc:
                    raise PlanPromotionError(
                        f"Slide {number}: candidate geometry is no longer valid: {exc}") from exc
                filename=row.get("wav")
                check(isinstance(filename,str)
                      and re.fullmatch(r"[A-Za-z0-9_.-]+\.wav",filename)
                      and filename not in used_wavs,
                      f"Slide {number}: missing/duplicate WAV name")
                used_wavs.add(filename)
                spoken="".join(fragments[i]["verbatim_script_fragment"] for i in ids).strip()
                check(len(spoken.split())>=4 and len(spoken)<2000,
                      f"Slide {number}: narration too short/long for valid stage")
                if not prepare_tts:
                    wav=audio/filename
                    check(wav.is_file() and not wav.is_symlink(),
                          f"Slide {number}: requested final audio does not exist")
                    with wave.open(str(wav),"rb") as f:
                        seconds=f.getnframes()/f.getframerate()
                        check(f.getcomptype()=="NONE" and 0.2<=seconds<=120,
                              f"Slide {number}: invalid/unbounded PCM narration")
                    # A matching filename is not evidence of voice or words.
                    proof_file=audio/(filename+".verified.json")
                    proof=load(proof_file)
                    check(proof.get("filename")==filename
                          and proof.get("wav_sha256")==file_hash(wav)
                          and proof.get("spoken_text_sha256")==hashlib.sha256(
                              spoken.encode("utf8")).hexdigest()
                          and proof.get("model")==declared_model
                          and proof.get("voice")==declared_voice,
                          f"Slide {number}: missing or mismatched Gemini TTS provenance")
                selections.append({"anchor":selected_anchor,"spoken_text":spoken,
                                   "wav":filename})
            check(used==required_ids,
                  f"Slide {number}: missing/repeated/out-of-order original narration words")
            authored.append({"slide":number,
                             "title":choice.get("title") or f"Original slide {number}",
                             "source_page":page_index,
                             "source_evidence":quote,
                             "elements":selections})
    groups=[];start=0
    for ending in boundaries+[len(authored)]:
        block=authored[start:ending]
        check(bool(block),"No empty video part")
        seconds=0
        for scene in block:
            for row in scene["elements"]:
                if prepare_tts:
                    # Conservative planning estimate, not recorded duration.
                    # Even an estimated sub-10m part MUST pass the later
                    # actual-WAV and decoded MP4 <600s gates.
                    seconds+=len(row["spoken_text"].split())*60/70
                else:
                    with wave.open(str(audio/row["wav"]),"rb") as wav:
                        seconds+=wav.getnframes()/wav.getframerate()
        check(0<seconds<(540 if prepare_tts else 590),
              "Part exceeds conservative TTS request or final video budget")
        groups.append({"part_id":f"part_{len(groups)+1:02d}","slides":block})
        start=ending
    # The stage contract deliberately does not represent semantic or
    # human-academic approval. The decision is only processing authorization.
    result={"schema_version":1,
            "status":("reviewed_element_tts_request_unapproved" if prepare_tts
                      else "author_specified_unapproved_element_narration"),
            "source_sha256":file_hash(source),
            "slides_sha256":file_hash(slides),
            "voice_id":voice,
            "parts":groups}
    if prepare_tts:
        result["tts_model"]=declared_model
        result["tts_voice"]=declared_voice
        result["script_sha256"]=file_hash(script)
        result["draft_sha256"]=file_hash(draft_path)
        result["review_selection_sha256"]=file_hash(selection)
        result["api_execution_authorized"]=False
        result["academic_approval"]=False
        result["student_publication"]=False
    elif tts_request is not None:
        from .element_narration_gemini import plan_hash
        req=load(Path(tts_request).resolve())
        check(req.get("status")=="reviewed_element_tts_request_unapproved"
              and req.get("tts_model")==declared_model
              and req.get("tts_voice")==declared_voice
              and req.get("script_sha256")==file_hash(script)
              and req.get("draft_sha256")==file_hash(draft_path)
              and req.get("review_selection_sha256")==file_hash(selection),
              "Prepared per-element TTS request differs from reviewed sources")
        expected=promoted(source=source,slides=slides,script=script,
            draft_path=draft_path,selection=selection,prepare_tts=True)
        check(req==expected,"Review-to-TTS request was edited or stale")
        identity=load(audio/"tts_job_identity.json")
        check(identity.get("plan_sha256")==plan_hash(req)
              and identity.get("model")==declared_model
              and identity.get("voice")==declared_voice
              and identity.get("segments")==[
                  e["wav"] for p in groups for sl in p["slides"] for e in sl["elements"]],
              "TTS synthesis job is not bound to exact reviewed element request")
        for item in (e for p in groups for sl in p["slides"] for e in sl["elements"]):
            proof=load(audio/(item["wav"]+".verified.json"))
            check(proof.get("plan_sha256")==plan_hash(req),
                  "Per-element TTS receipt refers to a different reviewed request")
    return result


def main(argv=None)->int:
    p=argparse.ArgumentParser(description=__doc__)
    sub=p.add_subparsers(dest="action",required=True)
    t=sub.add_parser("template")
    t.add_argument("--draft",required=True,type=Path)
    t.add_argument("--out",required=True,type=Path)
    r=sub.add_parser("prepare-tts")
    for n in ("source","slides","script","draft","selection","out"):
        r.add_argument("--"+n,required=True,type=Path)
    v=sub.add_parser("promote-reviewed")
    for n in ("source","slides","script","draft","selection","audio","out"):
        v.add_argument("--"+n,required=True,type=Path)
    v.add_argument("--tts-request",type=Path,
                   help="Verify real Gemini WAVs against exact pre-synthesis request")
    args=p.parse_args(argv)
    out=args.out.resolve()
    check(not out.exists() and out.parent.is_dir(),"Output must be new and isolated")
    if args.action=="template":
        draft=load(args.draft)
        proposal=template(draft)
        proposal["draft_sha256"]=file_hash(args.draft)
    else:
        check(not any(out.is_relative_to(getattr(args,n).resolve().parent)
                      for n in ("source","slides","script")),
              "Do not store candidate plans beside textbook source")
        proposal=promoted(source=args.source,slides=args.slides,script=args.script,
                 draft_path=args.draft,selection=args.selection,
                 audio=args.audio if args.action=="promote-reviewed" else None,
                 prepare_tts=args.action=="prepare-tts",
                 tts_request=args.tts_request if args.action=="promote-reviewed" else None)
    with out.open("x",encoding="utf8") as f:
        json.dump(proposal,f,indent=2,ensure_ascii=False);f.write("\n")
    print(json.dumps({"status":proposal["status"],
                      "slides":len(proposal.get("slides",[]))
                        if args.action=="template" else
                        sum(len(x["slides"]) for x in proposal["parts"]),
                      "stageable_only_if_frozen_wavs_are_verified":
                        args.action=="promote-reviewed",
                      "academic_approved":False}))
    return 0

if __name__=="__main__":raise SystemExit(main())
