"""Source-PDF numbered worked-example coverage guard, prior to paid TTS.

When an autogenerated outline explicitly promises source Examples 1–4,
reject a generated slide deck that silently omits Example 2. Validate
actual dedicated worked-example slide titles, not incidental references
on figures or the outline. Return actionable feedback for bounded Gemini
retry; this is not permission to invent an absent source example.
"""
from __future__ import annotations
import re
from pathlib import Path
import pymupdf

class ExampleCoverageError(ValueError):
    pass

SOURCE_EXAMPLE=re.compile(r"\bEXAMPLE\s+(\d{1,2})\b",re.I)
PROMISE=re.compile(
    r"\bExamples?\s+(\d{1,2})\s*(?:to|through|[-\u2013\u2014])\s*(\d{1,2})\b",
    re.I)
WORKED_FRAME=re.compile(
    r"\\begin\s*\{\s*frame\s*\}(?:\s*\[[^\]]*\])?"
    r"\s*\{\s*Example\s+(\d{1,2})\s*[:.\-\u2013]",
    re.I)

def original_examples(source:Path)->list[int]:
    if not source.is_file() or source.is_symlink():
        raise ExampleCoverageError("Source textbook PDF missing or symlinked")
    with pymupdf.open(source) as d:
        detected=set()
        for page in d:
            text=" ".join(page.get_text().split())
            detected.update(int(z) for z in SOURCE_EXAMPLE.findall(text))
    return sorted(detected)

def audit_latex_example_coverage(*,source_pdf:Path,slides_tex:str)->dict:
    source=original_examples(source_pdf)
    promises=set()
    for low,high in PROMISE.findall(slides_tex):
        a,b=int(low),int(high)
        if 1<=a<=b<=99 and b-a<=12:
            promises.update(range(a,b+1))
    presented=set(map(int,WORKED_FRAME.findall(slides_tex)))
    unsupported=sorted(promises-set(source))
    missing=sorted((promises & set(source))-presented)
    # Section title mentions aren't counted as an actual worked example.
    return {
        "status":"SOURCE_NUMBERED_EXAMPLE_COVERAGE_REVIEW",
        "source_examples":source,
        "explicitly_promised_examples":sorted(promises),
        "dedicated_worked_example_slide_titles":sorted(presented),
        "missing_promised_source_examples":missing,
        "unsupported_promised_example_numbers":unsupported,
        "coverage_pass":not missing and not unsupported,
        "ready_for_paid_TTS":not missing and not unsupported,
    }

def feedback(audit:dict)->str:
    missing=audit["missing_promised_source_examples"]
    extra=audit["unsupported_promised_example_numbers"]
    concerns=[]
    if missing:
        missing_titles=", ".join(f"Example {n}" for n in missing)
        concerns.append("SOURCE-COVERAGE REPAIR REQUIRED. Your outline explicitly promises "
            f"worked Examples {audit['explicitly_promised_examples']}, but your "
            f"full slides omit independent worked-example frames: {missing_titles}. "
            "These examples really occur in the attached ORIGINAL textbook source PDF. "
            "Preserve source mathematics exactly. Add a dedicated complete worked "
            "example frame titled 'Example N: ...' for EACH missing number, "
            "with source-grounded statement, derivation, domain assumptions, "
            "correct integrand and answer. Do not omit other source examples.")
    if extra:
        concerns.append(f"Your outline promises Examples {extra} absent from the "
                        "provided original textbook PDF; remove those unsupported claims.")
    return " ".join(concerns)

def require_coverage(*,source_pdf:Path,latex_path:Path)->dict:
    if not latex_path.is_file():
        raise ExampleCoverageError("Cannot perform source coverage before slides.tex")
    result=audit_latex_example_coverage(
        source_pdf=source_pdf,slides_tex=latex_path.read_text(encoding="utf8"))
    if not result["coverage_pass"]:
        raise ExampleCoverageError(feedback(result))
    return result
