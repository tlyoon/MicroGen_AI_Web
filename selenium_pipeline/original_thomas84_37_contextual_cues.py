def _actual_block(page,block_index:int,expected:str)->dict:
    blocks=page.get_text("blocks")
    require(type(block_index) is int and 0<=block_index<len(blocks),
            "Original PDF block is absent")
    block=blocks[block_index]
    require(block[6]==0 and len(block)>=7,
            "Selected candidate is not source-visible original text")
    text=str(block[4])
    cleaned=" ".join(text.split())
    require(expected.casefold() in cleaned.casefold(),
            "Source PDF does not contain the manually inspected anchor")
    rect=[float(block[k]) for k in range(4)]
    require(0<=rect[0]<rect[2]<=page.rect.width+.1 and
            0<=rect[1]<rect[3]<=page.rect.height+.1,
            "Physical PDF source candidate outside visual page")
    matches=[b for b in blocks if b[6]==0 and
             " ".join(str(b[4]).split())==cleaned and
             all(abs(float(b[k])-rect[k])<.01 for k in range(4))]
    require(len(matches)==1,"Original PDF source text and geometry ambiguous")
    return {"original_pdf_block_index":block_index,
            "original_pdf_visible_text":cleaned,
            "original_pdf_rect_pt":rect}

def build_contextual_source_cues(*,original:Path,existing_candidates:Path,
                                 release_guard:Path,out:Path)->dict:
    root=Path(original).resolve()
    candidates_path=Path(existing_candidates).resolve()
    guard_path=Path(release_guard).resolve()
    target=Path(out).absolute()
    require(root.is_dir() and candidates_path.is_file() and guard_path.is_file()
        and not candidates_path.is_symlink() and not guard_path.is_symlink()
        and target.parent.is_dir() and not target.exists()
        and not target.is_relative_to(root.parent),
        "Only source-read-only input and exclusive external output allowed")
    c=json.loads(candidates_path.read_text(encoding="utf8"))
    g=json.loads(guard_path.read_text(encoding="utf8"))
    require(c.get("status")==CANDIDATE_STATUS
        and c.get("source_pdf_sha256")==EXPECTED_SOURCE_SHA
        and c.get("student_publication_authorized") is False
        and g.get("historical_original_narration_utterances")==66
        and g.get("historical_utterances_with_no_element_mapping")==37
        and g.get("historical_utterances_with_provisional_pdf_mapping")==29
        and g.get("student_publication_authorized") is False
        and g.get("release_eligible") is False
        and file_hash(root/"source.pdf")==EXPECTED_SOURCE_SHA,
        "Protected source or original 37-missing provenance changed")
    missing={(x["slide"],x["sentence_index"]):x
             for x in g["original_unmapped_spoken_utterances"]}
    cuekeys={(slide,sentence) for slide,sentence,_,_,_ in SOURCE_CUES}
    require(len(SOURCE_CUES)==len(cuekeys)==37
            and set(missing)==cuekeys,
            "Explicit 37 original unlinked speech units changed")
    all_events={}
    for row in c["slides"]:
        for unit in row["candidate_segments"]:
            all_events[(row["slide"],unit["sentence_index"])]=unit
    proposals=[]
    with pymupdf.open(root/"slides.pdf") as deck:
        require(len(deck)==17,"Not 17 protected original slides")
        for slide,sentence,block_idx,anchor,support in SOURCE_CUES:
            event=all_events[(slide,sentence)]
            require(event["unique_target_review_priority"] is False
                    and event["eligible_for_final_student_highlight"] is False
                    and event["speech_to_visible_math_semantics_approved"] is False
                    and event["spoken_original_fragment_sha256"]==
                        missing[(slide,sentence)]["original_narration_fragment_sha256"]
                    and support in {"direct","contextual"},
                    "Attempt to override existing semantically unapproved candidates")
            source=_actual_block(deck[slide-1],block_idx,anchor)
            first=event["actual_recorded_word_start_second"]
            last=event["actual_recorded_word_end_second"]
            if first is not None:
                require(type(first) in (int,float)
                    and type(last) in (int,float)
                    and 0<=first<last,
                    "Real acoustic interval invalid")
                with wave.open(str(root/f"slide{slide}.wav"),"rb") as wav:
                    require(wav.getframerate()==24000 and
                            last<=wav.getnframes()/24000+.02,
                            "Real original WAV and proposed audible timing drift")
            else:
                require(first is None and last is None,
                        "Untimed source speech has invented audio timing")
            proposals.append({
                "slide":slide,
                "sentence_index":sentence,
                "original_narration_fragment_sha256":
                    event["spoken_original_fragment_sha256"],
                "actual_recorded_word_start_second":first,
                "actual_recorded_word_end_second":last,
                **source,
                "source_support_category":support,
                "source_mathematical_equivalence_independently_verified":False,
                "spoken_element_sync_release_approved":False,
                "student_publication_authorized":False,
            })
    require(len(proposals)==37
            and sum(p["actual_recorded_word_start_second"] is not None
                    for p in proposals)==36
            and file_hash(root/"source.pdf")==EXPECTED_SOURCE_SHA,
            "Untimed source inventory or original textbook changed")
    result={
        "schema_version":1,"status":STATUS,
        "original_textbook_sha256":EXPECTED_SOURCE_SHA,
        "original_slides_pdf_sha256":file_hash(root/"slides.pdf"),
        "pr335_candidate_receipt_sha256":file_hash(candidates_path),
        "pr344_release_guard_receipt_sha256":file_hash(guard_path),
        "previous_missing_unique_visual_targets":37,
        "physically_original_pdf_block_cues_proposed":37,
        "genuine_acoustic_word_timed_source_cue_proposals":36,
        "acoustically_untimed_title_source_cues":1,
        "mathematical_source_semantics_independently_approved":0,
        "student_publication_authorized":False,
        "release_eligible":False,
        "proposals":proposals,
    }
    require(not release_eligible({"actual_independently_audited_complete_videos":2,
        "historical_utterances_with_no_element_mapping":0,
        "historical_utterances_not_semantically_approved":66,
        "all_source_audio_video_consistency_accepted":True,
        "actual_each_video_under_600s":True}),
        "Physical PDF cues must never satisfy math-release gate")
    with target.open("x",encoding="utf8") as handle:
        json.dump(result,handle,indent=2,ensure_ascii=False)
        handle.write("\n")
    return result

def main():
    p=argparse.ArgumentParser(description=__doc__)
    for key in ("original","existing_candidates","release_guard","out"):
        p.add_argument("--"+key.replace("_","-"),type=Path,required=True)
    x=build_contextual_source_cues(**vars(p.parse_args()))
    print(json.dumps({k:v for k,v in x.items() if k!="proposals"},indent=2))
if __name__=="__main__": main()
